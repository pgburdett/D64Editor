namespace D64Editor.Core;

/// <summary>Standard C64 16-color palette (Pepto/VICE-compatible), shared by the bitmap/charset/sprite decoders.</summary>
public static class C64Colors
{
    public static readonly (byte R, byte G, byte B)[] Palette =
    {
        (0x00,0x00,0x00), (0xFF,0xFF,0xFF), (0x68,0x37,0x2B), (0x70,0xA4,0xB2),
        (0x6F,0x3D,0x86), (0x58,0x8D,0x43), (0x35,0x28,0x79), (0x7F,0xC0,0x4B),
        (0x43,0x28,0x24), (0x4E,0x4E,0x4E), (0x8E,0x8E,0x8E), (0x8A,0xB6,0x8E),
        (0x6F,0x6F,0xA2), (0xB5,0x6E,0x6E), (0x9A,0x9A,0x9A), (0xC8,0xC8,0xC8),
    };

    public static (byte R, byte G, byte B) Get(int index) =>
        (index >= 0 && index < Palette.Length) ? Palette[index] : Palette[0];
}
